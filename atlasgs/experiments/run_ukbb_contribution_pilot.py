#!/usr/bin/env python3
"""Run a small UKBB contribution pilot with per-branch timings.

The runner executes retained branches in a fixed order so later branches reuse
the T1/single/T1-guided artifacts generated by the baseline call. It writes
per-branch logs and timing JSON/CSV for stability and compute-cost reporting.
"""

import argparse
import csv
import json
import os
import subprocess
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from typing import Dict, List


def parse_csv_subjects(path: Path, max_subjects: int) -> List[str]:
    rows = path.read_text().strip().splitlines()
    subjects = []
    for row in rows[1:]:
        sid = row.split(",")[0].strip()
        if sid:
            subjects.append(sid)
    if max_subjects > 0:
        subjects = subjects[:max_subjects]
    return subjects


def parse_list(text: str) -> List[str]:
    return [x.strip() for x in str(text).split(",") if x.strip()]


def run_logged(cmd: List[str], log_path: Path, env: Dict[str, str]) -> Dict:
    log_path.parent.mkdir(parents=True, exist_ok=True)
    start = time.perf_counter()
    with log_path.open("w", encoding="utf-8") as log:
        log.write("$ " + " ".join(cmd) + "\n\n")
        log.flush()
        proc = subprocess.run(cmd, stdout=log, stderr=subprocess.STDOUT, env=env)
    elapsed = time.perf_counter() - start
    text = log_path.read_text(errors="ignore")
    return {
        "returncode": proc.returncode,
        "elapsed_sec": elapsed,
        "log": str(log_path),
        "nonfinite_mentions": text.lower().count("nan") + text.lower().count("inf"),
        "error_mentions": text.lower().count("error") + text.lower().count("traceback"),
    }


def base_cmd(args, subject: str, seed: int, out_root: Path) -> List[str]:
    return [
        "python",
        "-m",
        "atlasgs.experiments.run_subject",
        "--subject-id",
        subject,
        "--data-root",
        str(args.data_root),
        "--out-root",
        str(out_root),
        "--medgs-root",
        str(args.medgs_root),
        "--target-modalities",
        "flair",
        "--factor-z",
        str(args.factor_z),
        "--interp-factor",
        str(args.factor_z),
        "--train-iterations",
        str(args.iterations),
        "--t1guided-iterations",
        str(args.iterations),
        "--t1guided-topology-iterations",
        str(args.iterations),
        "--t1guided-latent-iterations",
        str(args.iterations),
        "--t1guided-our-iterations",
        str(args.iterations),
        "--t1guided-lambda-dssim",
        str(args.lambda_dssim),
        "--t1guided-topology-lambda-dssim",
        str(args.lambda_dssim),
        "--t1guided-our-lambda-dssim",
        str(args.lambda_dssim),
        "--t1guided-topology-persist-lambda",
        str(args.persist_lambda),
        "--seed",
        str(seed),
        "--t1guided-time-init-auto",
        "--no-run-alpine-a2",
    ]


def branch_cmd(args, subject: str, seed: int, out_root: Path, branch: str) -> List[str]:
    cmd = base_cmd(args, subject, seed, out_root)
    if branch == "baseline":
        cmd += ["--no-run-t1guided-our-fusion"]
        # Leave all optional branches disabled.
    elif branch == "topology":
        cmd += ["--run-t1guided-topology", "--no-run-t1guided-our-fusion"]
    elif branch == "latent":
        cmd += ["--run-t1guided-latent", "--no-run-t1guided-our-fusion"]
    elif branch == "all_raw":
        cmd += ["--run-t1guided-topology", "--run-t1guided-latent", "--run-t1guided-our", "--no-run-t1guided-our-fusion"]
    else:
        raise ValueError(branch)
    # Explicitly avoid LR-fusion; experiment 1 separately measures raw/fused
    # from the full existing dataset.
    return cmd


def run_unit(args, subject: str, seed: int, gpu_id: str) -> List[Dict]:
    out_root = args.out_root / f"seed{seed}"
    env = os.environ.copy()
    env["CUDA_VISIBLE_DEVICES"] = str(gpu_id)
    rows = []
    for branch in ["baseline", "topology", "latent", "all_raw"]:
        log_path = args.out_root / "logs" / f"{subject}_seed{seed}_{branch}.log"
        cmd = branch_cmd(args, subject, seed, out_root, branch)
        result = run_logged(cmd, log_path, env)
        row = {
            "subject": subject,
            "seed": seed,
            "branch": branch,
            "gpu": gpu_id,
            **result,
        }
        rows.append(row)
        if result["returncode"] != 0:
            break
    return rows


def write_rows(rows: List[Dict], out_root: Path) -> None:
    out_root.mkdir(parents=True, exist_ok=True)
    (out_root / "pilot_timings.json").write_text(json.dumps(rows, indent=2))
    with (out_root / "pilot_timings.csv").open("w", newline="", encoding="utf-8") as handle:
        fieldnames = ["subject", "seed", "branch", "gpu", "returncode", "elapsed_sec", "nonfinite_mentions", "error_mentions", "log"]
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow({k: row.get(k) for k in fieldnames})


def main() -> None:
    parser = argparse.ArgumentParser(description="Run UKBB z7 topology/latent contribution pilot.")
    parser.add_argument("--data-root", type=Path, required=True)
    parser.add_argument("--out-root", type=Path, required=True)
    parser.add_argument("--medgs-root", type=Path, required=True)
    parser.add_argument("--csv", type=Path, required=True)
    parser.add_argument("--max-subjects", type=int, default=2)
    parser.add_argument("--seeds", type=str, default="0,1,2")
    parser.add_argument("--gpu-ids", type=str, default="0")
    parser.add_argument("--factor-z", type=int, default=7)
    parser.add_argument("--iterations", type=int, default=2500)
    parser.add_argument("--lambda-dssim", type=float, default=0.2)
    parser.add_argument("--persist-lambda", type=float, default=10.0)
    args = parser.parse_args()

    subjects = parse_csv_subjects(args.csv, args.max_subjects)
    seeds = [int(x) for x in parse_list(args.seeds)]
    gpu_ids = parse_list(args.gpu_ids) or ["0"]
    tasks = [(s, seed, gpu_ids[i % len(gpu_ids)]) for i, (s, seed) in enumerate((s, seed) for seed in seeds for s in subjects)]
    args.out_root.mkdir(parents=True, exist_ok=True)
    (args.out_root / "pilot_manifest.json").write_text(
        json.dumps(
            {
                "subjects": subjects,
                "seeds": seeds,
                "gpu_ids": gpu_ids,
                "iterations": args.iterations,
                "factor_z": args.factor_z,
                "persist_lambda": args.persist_lambda,
            },
            indent=2,
        )
    )

    all_rows: List[Dict] = []
    with ThreadPoolExecutor(max_workers=len(gpu_ids)) as ex:
        futures = [ex.submit(run_unit, args, subject, seed, gpu) for subject, seed, gpu in tasks]
        for future in as_completed(futures):
            rows = future.result()
            all_rows.extend(rows)
            write_rows(all_rows, args.out_root)
            if any(row["returncode"] != 0 for row in rows):
                raise SystemExit(f"Contribution pilot failed; see {args.out_root / 'pilot_timings.csv'}")
    write_rows(all_rows, args.out_root)


if __name__ == "__main__":
    main()
